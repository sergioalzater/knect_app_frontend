@Injectable({ providedIn: 'root' })
export class I18nService {
  private readonly platformId = inject(PLATFORM_ID);
  private readonly document = inject(DOCUMENT);
  readonly lang = signal<AppLanguage>('es');

  constructor() {
    if (isPlatformBrowser(this.platformId)) {
      const saved = localStorage.getItem('knect_lang') as AppLanguage | null;
      if (saved === 'es' || saved === 'en') {
        this.lang.set(saved);
      }
    }
    this.syncDocumentLang();
  }

  setLang(language: AppLanguage): void {
    this.lang.set(language);
    if (isPlatformBrowser(this.platformId)) {
      localStorage.setItem('knect_lang', language);
    }
    this.syncDocumentLang();
  }

  toggleLang(): void {
    this.setLang(this.lang() === 'es' ? 'en' : 'es');
  }

  t(key: string): string {
    const current = this.lang();
    return DICTIONARY[current][key] ?? key;
  }

  /** Mantiene <html lang> sincronizado para lectores de pantalla y traductores (WCAG 3.1.1). */
  private syncDocumentLang(): void {
    this.document.documentElement.lang = this.lang();
  }
}
